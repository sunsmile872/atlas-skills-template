"""
Master Presenter Notes Generator (PPTX Injector + Markdown + Word DOCX)
Generated by pmr-slide-creator skill
"""

import os
import sys
import glob
import importlib
from pptx import Presentation
import docx
from docx.shared import Inches, Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml import OxmlElement
from docx.oxml.ns import qn

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
PPTX_PATH = os.path.join(BASE_DIR, "{{PPTX_FILENAME}}")
LOCAL_DOCX = os.path.join(BASE_DIR, "{{DOCX_FILENAME}}")
MD_PATH = os.path.join(BASE_DIR, "PRESENTER_NOTES_MASTER.md")
NOTES_LANG = "{{NOTES_LANG}}"  # "en" (Journal Club default) or "th" (Topic/Board Lecture default)
IS_EN = NOTES_LANG.lower().startswith("en")

MODULES_DIR = os.path.join(BASE_DIR, "notes_data_modules")
if MODULES_DIR not in sys.path:
    sys.path.append(MODULES_DIR)

NOTES_DATA = {}
if os.path.exists(MODULES_DIR):
    for py_file in sorted(glob.glob(os.path.join(MODULES_DIR, "mod*.py"))):
        mod_name = os.path.splitext(os.path.basename(py_file))[0]
        mod = importlib.import_module(mod_name)
        if hasattr(mod, "DATA"):
            NOTES_DATA.update(mod.DATA)


def set_cell_background(cell, hex_color):
    tcPr = cell._element.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hex_color)
    tcPr.append(shd)


def set_cell_margins(cell, top=100, bottom=100, left=150, right=150):
    tcPr = cell._element.get_or_add_tcPr()
    tcMar = OxmlElement("w:tcMar")
    for m, val in [("top", top), ("bottom", bottom), ("left", left), ("right", right)]:
        node = OxmlElement(f"w:{m}")
        node.set(qn("w:w"), str(val))
        node.set(qn("w:type"), "dxa")
        tcMar.append(node)
    tcPr.append(tcMar)


def inject_notes_to_pptx():
    prs = Presentation(PPTX_PATH)
    for idx, slide in enumerate(prs.slides, 1):
        info = NOTES_DATA.get(idx)
        if not info:
            continue
        if IS_EN:
            notes_text = (
                f"[{info['time']}] {info['title']}\n\n"
                f"[Spoken Script]:\n{info['script']}\n\n"
                f"[Staff Q&A Defense]:\n{info['trap']}\n\n"
                f"[Transition]: {info['trans']}"
            )
        else:
            notes_text = (
                f"[{info['time']}] {info['title']}\n\n"
                f"【บทพูดบรรยาย】:\n{info['script']}\n\n"
                f"【Staff Q&A Trap】:\n{info['trap']}\n\n"
                f"【Transition】: {info['trans']}"
            )
        slide.notes_slide.notes_text_frame.text = notes_text
    prs.save(PPTX_PATH)
    print(f"SUCCESS: Injected presenter notes into {PPTX_PATH} ({len(prs.slides)} slides)")


def generate_markdown():
    if IS_EN:
        md_lines = [
            "# Master Presenter Notes & Staff Q&A Defense Suite (English)",
            "## {{TOPIC_TITLE}}",
            "**Speaker**: {{PRESENTER_NAME}} (PM&R Resident Year 1)  ",
            "**Supervisor**: {{ADVISOR_NAME}}  ",
            "**Institution**: Department of Rehabilitation Medicine, {{INSTITUTION}}  \n",
            "---",
            "",
        ]
        for idx in sorted(NOTES_DATA.keys()):
            info = NOTES_DATA[idx]
            md_lines.append(f"### Slide {idx:02d} | {info['title']} ({info['time']})")
            md_lines.append(f"**Spoken Script**:\n> {info['script']}\n")
            md_lines.append(f"**Staff Q&A Defense**:\n```text\n{info['trap']}\n```\n")
            md_lines.append(f"*Transition*: `{info['trans']}`\n")
            md_lines.append("---\n")
    else:
        md_lines = [
            "# Master Presenter Notes & Staff Q&A Defense Suite",
            "## {{TOPIC_TITLE}}",
            "**Speaker**: {{PRESENTER_NAME}} (Resident PM&R Year 1)  ",
            "**Advisor**: {{ADVISOR_NAME}}  ",
            "**Institution**: {{INSTITUTION}}, Faculty of Medicine, {{UNIVERSITY}}  \n",
            "---",
            "",
        ]
        for idx in sorted(NOTES_DATA.keys()):
            info = NOTES_DATA[idx]
            md_lines.append(f"### Slide {idx:02d}: {info['title']} ({info['time']})")
            md_lines.append(f"**บทพูดบรรยาย**:\n> {info['script']}\n")
            md_lines.append(f"**Staff Q&A Defense Trap**:\n```text\n{info['trap']}\n```\n")
            md_lines.append(f"*Transition*: `{info['trans']}`\n")
            md_lines.append("---\n")
    with open(MD_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(md_lines))
    print(f"SUCCESS: Generated {MD_PATH}")


def generate_docx():
    doc = docx.Document()
    for s in doc.sections:
        s.top_margin = Inches(0.75)
        s.bottom_margin = Inches(0.75)
        s.left_margin = Inches(0.75)
        s.right_margin = Inches(0.75)

    p_title = doc.add_paragraph()
    p_title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    font_name = "Calibri" if IS_EN else "Arial"
    r_title = p_title.add_run("{{TOPIC_TITLE}}\n")
    r_title.font.name = font_name
    r_title.font.size = Pt(16 if IS_EN else 20)
    r_title.font.bold = True
    r_title.font.color.rgb = RGBColor(15, 23, 42)

    sub_str = (
        f"Master Presenter Notes & Staff Q&A Defense Suite ({len(NOTES_DATA)} Slides, Spoken English)\n"
        if IS_EN
        else "Master Presenter Notes & Staff Q&A Defense Suite\n"
    )
    r_sub = p_title.add_run(sub_str)
    r_sub.font.name = font_name
    r_sub.font.size = Pt(12 if IS_EN else 13)
    r_sub.font.bold = True
    r_sub.font.color.rgb = RGBColor(13, 148, 136)

    lbl_script = "Spoken Script" if IS_EN else "【บทพูดบรรยาย】"
    lbl_trap = "Staff Q&A Defense" if IS_EN else "【Staff Q&A Defense Trap】"

    for idx in sorted(NOTES_DATA.keys()):
        info = NOTES_DATA[idx]
        p_head = doc.add_paragraph()
        p_head.paragraph_format.space_before = Pt(10)
        p_head.paragraph_format.space_after = Pt(4)
        p_head.paragraph_format.keep_with_next = True
        r_num = p_head.add_run(f"Slide {idx:02d} | " if IS_EN else f"Slide {idx:02d}: ")
        r_num.font.name = font_name
        r_num.font.size = Pt(12 if IS_EN else 13)
        r_num.font.bold = True
        r_num.font.color.rgb = RGBColor(13, 148, 136)

        r_htitle = p_head.add_run(f"{info['title']}  [{info['time']}]")
        r_htitle.font.name = font_name
        r_htitle.font.size = Pt(12 if IS_EN else 13)
        r_htitle.font.bold = True
        r_htitle.font.color.rgb = RGBColor(15, 23, 42)

        tbl = doc.add_table(rows=3, cols=2)
        tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
        tbl.autofit = False
        col_w = [Inches(1.55), Inches(5.45)]
        rows_content = [
            (lbl_script, info["script"], "F8FAFC"),
            (lbl_trap, info["trap"], "F0FDFA"),
            ("Transition", info["trans"], "FFFFFF"),
        ]
        for r_i, (label, body, bg_hex) in enumerate(rows_content):
            row = tbl.rows[r_i]
            trPr = row._tr.get_or_add_trPr()
            trPr.append(OxmlElement("w:cantSplit"))
            c0, c1 = row.cells[0], row.cells[1]
            c0.width, c1.width = col_w[0], col_w[1]
            set_cell_background(c0, "E2E8F0")
            set_cell_background(c1, bg_hex)
            set_cell_margins(c0, 80, 80, 120, 120)
            set_cell_margins(c1, 80, 80, 120, 120)

            p0 = c0.paragraphs[0]
            r0 = p0.add_run(label)
            r0.font.name = font_name
            r0.font.size = Pt(10.5)
            r0.font.bold = True
            r0.font.color.rgb = RGBColor(15, 23, 42)

            p1 = c1.paragraphs[0]
            r1 = p1.add_run(body)
            r1.font.name = font_name
            r1.font.size = Pt(10.5)
            r1.font.color.rgb = RGBColor(30, 41, 59)

    doc.save(LOCAL_DOCX)
    print(f"SUCCESS: Generated {LOCAL_DOCX}")

    try:
        import sync_to_drive
        sync_to_drive.sync()
    except Exception as e:
        print(f"WARNING: Google Drive sync skipped: {e}")


import argparse

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Inject speaker notes into PPTX and build PRESENTER_NOTES_MASTER.md")
    parser.add_argument("--docx", action="store_true", help="Also generate standalone Word .docx on explicit demand")
    args = parser.parse_args()

    inject_notes_to_pptx()
    generate_markdown()
    if args.docx:
        generate_docx()
    else:
        print("INFO: Skipping .docx export (default .pptx Speaker Notes + PRESENTER_NOTES_MASTER.md; pass --docx if needed).")
