def set_theme(theme_name, custom_palette=None):
    global COLOR_BG_WHITE, COLOR_BG_LIGHT, COLOR_BORDER, COLOR_NAVY_DARK, COLOR_NAVY_MID
    global COLOR_TEXT_MAIN, COLOR_TEXT_MUTED, COLOR_TEAL, COLOR_TEAL_LIGHT, COLOR_TEAL_DARK
