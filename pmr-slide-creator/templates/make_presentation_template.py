def add_jc_checklist_slide(prs, title_text, checklist_img, verdicts, ref_text=""):
    """
    1 Checklist Section per slide (Official CASP UK 2024 or NIH NHLBI crop left h=6.10 in;
    clean verdict badges + short keyword rationale cards on right).
    verdicts: list of tuples (question_label, verdict_str, rationale_str)
    """
    from PIL import Image

    slide = prs.slides.add_slide(prs.slide_layouts[6])
    bg = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(0), Inches(0), Inches(13.333), Inches(7.5))
