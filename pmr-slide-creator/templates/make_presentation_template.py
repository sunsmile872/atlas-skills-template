    card_x = max(pic_right, 5.65)
    card_w = 12.78 - card_x
    n = max(1, len(verdicts))
    gap = 0.16
    row_h = min(1.38, (5.95 - gap * (n - 1)) / n)

    for idx, (q_lbl, v_str, reason) in enumerate(verdicts):
        ry = 0.90 + idx * (row_h + gap)
        vc, vbg = _classify_jc_verdict_style(v_str)

        card = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(card_x), Inches(ry), Inches(card_w), Inches(row_h))
