def get_asset(filename):
    if not filename:
        return None
    path = os.path.join(ASSET_DIR, filename)
    return path if os.path.exists(path) else None


def init_presentation():
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    return prs


def add_header(slide, category_text, title_text, subtitle_text=""):
    cat_box = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(0.8), Inches(0.38), Inches(3.8), Inches(0.32))
    cat_box.fill.solid()
    cat_box.fill.fore_color.rgb = COLOR_TEAL_LIGHT
    cat_box.line.color.rgb = COLOR_TEAL
    cat_box.line.width = Pt(1)
    tf = cat_box.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    p = tf.paragraphs[0]
    p.text = category_text.upper()
    p.alignment = PP_ALIGN.CENTER
    p.font.name = FONT_HEADING
    p.font.size = Pt(9.5)
    p.font.bold = True
    p.font.color.rgb = COLOR_TEAL_DARK

    tb = slide.shapes.add_textbox(Inches(0.8), Inches(0.74), Inches(11.733), Inches(0.72))
    tf2 = tb.text_frame
    tf2.word_wrap = True
    tf2.margin_left = tf2.margin_top = tf2.margin_right = tf2.margin_bottom = 0
    p1 = tf2.paragraphs[0]
    p1.text = title_text
    p1.font.name = FONT_HEADING
    p1.font.size = Pt(24)
    p1.font.bold = True
    p1.font.color.rgb = COLOR_NAVY_DARK

    if subtitle_text:
        p2 = tf2.add_paragraph()
        p2.text = subtitle_text
        p2.font.name = FONT_BODY
        p2.font.size = Pt(13.5)
        p2.font.color.rgb = COLOR_TEXT_MUTED
        p2.space_before = Pt(2)


def add_footnote(slide, ref_text):
    tb = slide.shapes.add_textbox(Inches(0.8), Inches(7.08), Inches(11.733), Inches(0.32))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_top = tf.margin_right = tf.margin_bottom = 0
    p = tf.paragraphs[0]
    p.text = f"Ref: {ref_text}"
    p.font.name = FONT_BODY
    p.font.size = Pt(9.5)
    p.font.italic = True
    p.font.color.rgb = COLOR_TEXT_MUTED


