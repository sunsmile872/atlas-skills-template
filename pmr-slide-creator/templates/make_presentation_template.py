def _classify_jc_verdict_style(verdict_str):
    """Classify CASP/NIH verdict string cleanly without substring false positives (e.g., 'cannot' matching 'no')."""
    import re
    v_low = (verdict_str or "").lower().strip()
    if re.search(r"\b(can'?t\s*tell|cannot\s*tell|cannot|unclear|consider|not\s*reported|n/?a|partial)\b", v_low):
        return JC_AMBER_ACCENT, JC_AMBER_BG
    if re.search(r"\byes\b", v_low):
        return COLOR_TEAL_DARK, COLOR_TEAL_LIGHT
    if re.search(r"\bno\b", v_low):
        return JC_CORAL_RED, JC_ROSE_BG
    return JC_AMBER_ACCENT, JC_AMBER_BG


