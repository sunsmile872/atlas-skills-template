def finalize_jc_slide_numbers(prs):
    """Stamp bottom-right `01 / N` slide numbers on all JC slides that lack one."""
    total = len(prs.slides)
    for idx, slide in enumerate(prs.slides, 1):
        already = False
        for sh in slide.shapes:
            if sh.has_text_frame and (sh.top / 914400) >= 6.95 and (sh.left / 914400) >= 11.0:
                if "/" in sh.text_frame.text:
                    already = True
                    break
        if already:
            continue
        is_dark = idx == 1
        nb = slide.shapes.add_textbox(Inches(11.65), Inches(7.12), Inches(1.13), Inches(0.26))
        ntf = nb.text_frame
        ntf.word_wrap = False
        ntf.margin_left = ntf.margin_top = ntf.margin_right = ntf.margin_bottom = 0
        p = ntf.paragraphs[0]
        p.text = f"{idx:02d} / {total:02d}"
        p.alignment = PP_ALIGN.RIGHT
        p.font.name = FONT_BODY
        p.font.size = Pt(9.5)
        p.font.bold = True
        p.font.color.rgb = RGBColor(148, 163, 184) if is_dark else COLOR_TEXT_MUTED


