def add_split_content_slide(
    prs,
    category,
    title,
    subtitle,
    bullets,
    image_file=None,
    figure_title=None,
    figure_source=None,
    footnote=None,
    pearl=None,
    left_width=None,
    right_left=None,
    right_width=None,
    pic_max_height=None,
    cap_top_pos=None,
):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    add_header(slide, category, title, subtitle)

    img_path = get_asset(image_file) if image_file else None
    card_h = Inches(5.35)

    if img_path:
        left_w = left_width if left_width is not None else Inches(6.00)
        right_l = right_left if right_left is not None else Inches(7.033)
        right_w = right_width if right_width is not None else Inches(5.50)
    else:
        left_w = Inches(11.733)
        right_l = None
        right_w = None

    card = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(0.8), Inches(1.55), left_w, card_h)
    card.fill.solid()
    card.fill.fore_color.rgb = COLOR_BG_WHITE
    card.line.color.rgb = COLOR_BORDER
    card.line.width = Pt(1)

    tb = slide.shapes.add_textbox(Inches(1.02), Inches(1.68), left_w - Inches(0.35), card_h - Inches(0.25))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_top = tf.margin_right = tf.margin_bottom = 0

    clean_bullets = [(h, d) for (h, d) in bullets if "Clinical Pearl" not in h]

    for i, (b_head, b_desc) in enumerate(clean_bullets):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        if b_desc == "":
            p.space_before = Pt(0) if i == 0 else Pt(14)
            p.line_spacing = 1.15
            run_h = p.add_run()
            run_h.text = f"■  {b_head}"
            run_h.font.name = FONT_HEADING
            run_h.font.size = Pt(16.5)
            run_h.font.bold = True
            run_h.font.color.rgb = COLOR_TEAL_DARK
        else:
            p.space_before = Pt(6) if i > 0 else Pt(0)
            p.line_spacing = 1.15
            run_h = p.add_run()
            run_h.text = f"   •  {b_head}: "
            run_h.font.name = FONT_HEADING
            run_h.font.size = Pt(16.0)
            run_h.font.bold = True
            run_h.font.color.rgb = COLOR_NAVY_MID

            run_d = p.add_run()
            run_d.text = b_desc
            run_d.font.name = FONT_BODY
            run_d.font.size = Pt(14.0)
            run_d.font.color.rgb = COLOR_TEXT_MAIN

    if img_path:
        img_card = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, right_l, Inches(1.55), right_w, card_h)
        img_card.fill.solid()
        img_card.fill.fore_color.rgb = COLOR_BG_WHITE
        img_card.line.color.rgb = COLOR_BORDER
        img_card.line.width = Pt(1)

        pic_max_w = right_w - Inches(0.16)
        pic_max_h = pic_max_height if pic_max_height is not None else Inches(4.62)
        pic_top_start = Inches(1.66)
        pic = slide.shapes.add_picture(img_path, right_l + Inches(0.08), pic_top_start, width=pic_max_w)

        if pic.height > pic_max_h:
            ratio = pic_max_h / pic.height
            pic.height = pic_max_h
            pic.width = int(pic.width * ratio)
            pic.left = int(right_l + (right_w - pic.width) / 2)
        else:
            pic.left = int(right_l + (right_w - pic.width) / 2)
            pic.top = int(pic_top_start + (pic_max_h - pic.height) / 2)

        cap_top = cap_top_pos if cap_top_pos is not None else Inches(6.32)
        cap_h = Inches(0.48) if cap_top_pos is None else Inches(0.55)
        tb_cap = slide.shapes.add_textbox(right_l + Inches(0.08), cap_top, right_w - Inches(0.16), cap_h)
        tf_cap = tb_cap.text_frame
        tf_cap.word_wrap = True
        tf_cap.margin_left = tf_cap.margin_top = tf_cap.margin_right = tf_cap.margin_bottom = 0

        p_cap1 = tf_cap.paragraphs[0]
        p_cap1.text = figure_title or "Textbook Illustration"
        p_cap1.alignment = PP_ALIGN.CENTER
        p_cap1.font.name = FONT_HEADING
        p_cap1.font.size = Pt(10.5)
        p_cap1.font.bold = True
        p_cap1.font.color.rgb = COLOR_NAVY_MID

        p_cap2 = tf_cap.add_paragraph()
        p_cap2.text = f"Source: {figure_source}" if figure_source else "Source: Reference Textbook"
        p_cap2.alignment = PP_ALIGN.CENTER
        p_cap2.font.name = FONT_BODY
        p_cap2.font.size = Pt(9.5)
        p_cap2.font.italic = True
        p_cap2.font.color.rgb = COLOR_TEXT_MUTED
        p_cap2.space_before = Pt(2)

    if footnote:
        add_footnote(slide, footnote)


def add_content_slide(prs, category, title, subtitle, bullets, footnote=None):
    """Full-width content card slide when no textbook image/table is needed (Smart 3-Way Rule Case 3)."""
    return add_split_content_slide(
        prs,
        category=category,
        title=title,
        subtitle=subtitle,
        bullets=bullets,
        image_file=None,
        footnote=footnote,
    )


def add_table_slide(prs, category, title, subtitle, headers, rows, col_widths, footnote=None, pearl=None):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    add_header(slide, category, title, subtitle)

    table_top = Inches(1.55)
    table_left = Inches(0.8)
    table_w = Inches(11.733)
    table_h = Inches(4.5) if pearl else Inches(5.35)

    table_shape = slide.shapes.add_table(len(rows) + 1, len(headers), table_left, table_top, table_w, table_h)
    table = table_shape.table

    for i, w in enumerate(col_widths):
        table.columns[i].width = Inches(w)

    for col_idx, header_text in enumerate(headers):
        cell = table.cell(0, col_idx)
        cell.fill.solid()
        cell.fill.fore_color.rgb = COLOR_NAVY_DARK
        cell.vertical_anchor = MSO_ANCHOR.MIDDLE
        cell.margin_left = cell.margin_right = cell.margin_top = cell.margin_bottom = Inches(0.08)
        p = cell.text_frame.paragraphs[0]
        p.text = header_text
        p.alignment = PP_ALIGN.CENTER
        p.font.name = FONT_HEADING
        p.font.size = Pt(11)
        p.font.bold = True
        p.font.color.rgb = COLOR_BG_WHITE

    for row_idx, row_data in enumerate(rows):
        bg_color = COLOR_BG_LIGHT if row_idx % 2 == 1 else COLOR_BG_WHITE
        for col_idx, cell_value in enumerate(row_data):
            cell = table.cell(row_idx + 1, col_idx)
            cell.fill.solid()
            cell.fill.fore_color.rgb = bg_color
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            cell.margin_left = cell.margin_right = cell.margin_top = cell.margin_bottom = Inches(0.08)
            p = cell.text_frame.paragraphs[0]
            p.text = str(cell_value)
            p.font.name = FONT_BODY
            p.font.size = Pt(10)
            if col_idx == 0:
                p.font.bold = True
                p.font.color.rgb = COLOR_NAVY_MID
                p.alignment = PP_ALIGN.LEFT
            else:
                p.font.color.rgb = COLOR_TEXT_MAIN
                p.alignment = PP_ALIGN.LEFT

    if footnote:
        add_footnote(slide, footnote)


def add_algorithm_slide(prs, category, title, subtitle, stages, footnote=None):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    add_header(slide, category, title, subtitle)

    num_stages = len(stages)
    stage_w = (11.733 - (num_stages - 1) * 0.3) / num_stages
    left_pos = 0.8

    for idx, stg in enumerate(stages):
        card = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(left_pos), Inches(1.55), Inches(stage_w), Inches(5.35))
        card.fill.solid()
