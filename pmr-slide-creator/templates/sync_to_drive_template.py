#!/usr/bin/env python3
"""
Sync Master Presentation PPTX and Presenter Notes DOCX to Google Drive.
Generated by pmr-slide-creator skill.
"""
import os
import shutil
from datetime import datetime

LOCAL_DIR = os.path.dirname(os.path.abspath(__file__))
DRIVE_DIR = "~/Library/CloudStorage/GoogleDrive-{{USER_EMAIL}}/My Drive/Resident Rehab"

PPTX_NAME = "{{PPTX_FILENAME}}"
MD_NAME = "PRESENTER_NOTES_MASTER.md"
DOCX_NAME = "{{DOCX_FILENAME}}"


def sync():
    if not os.path.exists(DRIVE_DIR):
        print(f"WARNING: Google Drive folder not mounted at: {DRIVE_DIR}")
        return False

    for fname in (PPTX_NAME, MD_NAME, DOCX_NAME):
        local_f = os.path.join(LOCAL_DIR, fname)
        drive_f = os.path.join(DRIVE_DIR, fname)
        if os.path.exists(local_f):
            shutil.copy2(local_f, drive_f)
            print(f"SUCCESS: Synced -> Google Drive: {fname}")

    print(f"Sync completed at {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    return True


if __name__ == "__main__":
    sync()
